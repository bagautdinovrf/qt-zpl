constexpr char32_t fontACharacter(char32_t ch) noexcept {
    // Font A's printer character 0x5c is the cent sign.
    return ch == U'\\' ? U'\u00a2' : ch;
}
constexpr FontATransform fontATransform(char32_t ch) noexcept {
    if(ch == U'\u25af') return {35.0/33.0,35.0/33.0,-82,0};
    return ch >= 32 && ch <= 126 ? fontATransforms[ch - 32] : FontATransform{35.0/33.0,35.0/33.0,0,0};
}
